// Command notices writes THIRD-PARTY-NOTICES.txt: the license of every module compiled into the
// Windows and Linux builds, plus the Go standard library's. Their licenses (MIT, BSD, Apache-2.0)
// require shipping these texts with the binaries; CI checks the file is current and attaches it
// to every release.
//
//	go run ./tools/notices
//
// Run it from the repository root after adding, removing or updating a dependency.
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct{ path, version, dir string }

func main() {
	mods := map[string]module{}
	for _, goos := range []string{"windows", "linux"} {
		cmd := exec.Command("go", "list", "-deps", "-f",
			"{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", "./pkg/deej/cmd")
		cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH=amd64", "CGO_ENABLED=0")
		cmd.Stderr = os.Stderr
		out, err := cmd.Output()
		if err != nil {
			fail("go list: %v", err)
		}
		for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if f := strings.Split(line, "\t"); len(f) == 3 {
				mods[f[0]] = module{f[0], f[1], f[2]}
			}
		}
	}
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString("deej includes the following third-party software.\n" +
		"This file is generated by `go run ./tools/notices`; do not edit it by hand.\n")
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		fail("go env GOROOT: %v", err)
	}
	section(&b, "The Go standard library and runtime (https://go.dev)", strings.TrimSpace(string(goroot)))
	for _, p := range paths {
		m := mods[p]
		section(&b, m.path+" "+m.version, m.dir)
	}
	if err := os.WriteFile("THIRD-PARTY-NOTICES.txt", []byte(b.String()), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("THIRD-PARTY-NOTICES.txt: %d modules + the Go standard library\n", len(paths))
}

// section appends a heading and the license (plus NOTICE, for Apache-2.0) found in dir.
func section(b *strings.Builder, title, dir string) {
	found := false
	for _, names := range [][]string{
		{"LICENSE", "LICENSE.txt", "LICENSE.md", "LICENCE", "COPYING", "LICENSE-MIT"},
		{"NOTICE", "NOTICE.txt", "NOTICE.md"},
	} {
		for _, name := range names {
			text, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				continue
			}
			if !found {
				fmt.Fprintf(b, "\n%s\n%s\n%s\n\n", strings.Repeat("=", 78), title, strings.Repeat("=", 78))
			} else {
				b.WriteString("\n") // NOTICE after LICENSE
			}
			b.WriteString(strings.TrimSpace(strings.ReplaceAll(string(text), "\r\n", "\n")) + "\n")
			found = true
			break
		}
	}
	if !found {
		fail("no license file found for %s in %s", title, dir)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "notices: "+format+"\n", args...)
	os.Exit(1)
}
